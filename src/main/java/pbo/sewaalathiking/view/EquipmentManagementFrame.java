    private void setupTable() {
        DefaultTableModel model = new DefaultTableModel(
            new Object[]{"ID", "Nama Alat", "Kategori", "Harga/Hari", "Total Stok", "Stok Tersedia"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tabelAlat.setModel(model);
    }
    private void loadDataAlat() {
        DefaultTableModel model = (DefaultTableModel) tabelAlat.getModel();
        model.setRowCount(0);

        equipmentList = equipmentRepo.getAllEquipment();
        for (Equipment eq : equipmentList) {
            model.addRow(new Object[]{
                eq.getId(),
                eq.getName(),
                eq.getCategory(),
                eq.getPricePerDay(),
                eq.getTotalStock(),
                eq.getAvailableStock()
            });
        }
    }
