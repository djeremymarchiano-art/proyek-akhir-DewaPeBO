    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        String nama = fieldNama.getText().trim();
        String kategori = comboKategori.getSelectedItem().toString();
        String hargaStr = fieldHarga.getText().trim();
        String totalStr = fieldTotalStok.getText().trim();

        if (nama.isEmpty() || hargaStr.isEmpty() || totalStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama, Harga, dan Total Stok wajib diisi!");
            return;
        }
        try {
            double harga = Double.parseDouble(hargaStr);
            int totalStok = Integer.parseInt(totalStr);
            int stokTersedia = fieldStokTersedia.getText().trim().isEmpty()
                    ? totalStok
                    : Integer.parseInt(fieldStokTersedia.getText().trim());

            if (harga < 0 || totalStok < 0 || stokTersedia < 0 || stokTersedia > totalStok) {
                JOptionPane.showMessageDialog(this, "Periksa kembali nilai harga dan stok (stok tersedia tidak boleh melebihi total stok)!");
                return;
            }

            Equipment eq = new Equipment(0, nama, kategori, harga, totalStok, stokTersedia);
            if (equipmentRepo.addEquipment(eq)) {
                JOptionPane.showMessageDialog(this, "Alat berhasil ditambahkan!");
                loadDataAlat();
                resetForm();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal menambah alat.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga dan Stok harus berupa angka!");
        }
    }//GEN-LAST:event_btnTambahActionPerformed

    private void tabelAlatMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelAlatMouseClicked
        int row = tabelAlat.getSelectedRow();
        if (row != -1) {
            selectedEquipmentId = Integer.parseInt(tabelAlat.getValueAt(row, 0).toString());
            fieldNama.setText(tabelAlat.getValueAt(row, 1).toString());
            comboKategori.setSelectedItem(tabelAlat.getValueAt(row, 2).toString());
            fieldHarga.setText(String.format("%.0f", Double.parseDouble(tabelAlat.getValueAt(row, 3).toString())));
            fieldTotalStok.setText(tabelAlat.getValueAt(row, 4).toString());
            fieldStokTersedia.setText(tabelAlat.getValueAt(row, 5).toString());
        }
    }//GEN-LAST:event_tabelAlatMouseClicked

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        if (selectedEquipmentId == -1) {
            JOptionPane.showMessageDialog(this, "Pilih alat dari tabel yang ingin diubah terlebih dahulu!");
            return;
        }

        try {
            String nama = fieldNama.getText().trim();
            String kategori = comboKategori.getSelectedItem().toString();
            double harga = Double.parseDouble(fieldHarga.getText().trim());
            int totalStok = Integer.parseInt(fieldTotalStok.getText().trim());
            int stokTersedia = Integer.parseInt(fieldStokTersedia.getText().trim());

            if (nama.isEmpty() || harga < 0 || totalStok < 0 || stokTersedia < 0 || stokTersedia > totalStok) {
                JOptionPane.showMessageDialog(this, "Input tidak valid! Pastikan stok tersedia <= total stok.");
                return;
            }

            Equipment eq = new Equipment(selectedEquipmentId, nama, kategori, harga, totalStok, stokTersedia);
            if (equipmentRepo.updateEquipment(eq)) {
                JOptionPane.showMessageDialog(this, "Data alat berhasil diperbarui!");
                loadDataAlat();
                resetForm();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal mengubah data alat.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga dan Stok harus berupa angka!");
        }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if (selectedEquipmentId == -1) {
            JOptionPane.showMessageDialog(this, "Pilih alat dari tabel yang ingin dihapus!");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
            "Yakin ingin menghapus alat \"" + fieldNama.getText() + "\"?\nRiwayat transaksi terkait alat ini juga akan terhapus.",
            "Konfirmasi Hapus",
            JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            if (equipmentRepo.deleteEquipment(selectedEquipmentId)) {
                JOptionPane.showMessageDialog(this, "Alat berhasil dihapus!");
                loadDataAlat();
                resetForm();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal menghapus alat.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

