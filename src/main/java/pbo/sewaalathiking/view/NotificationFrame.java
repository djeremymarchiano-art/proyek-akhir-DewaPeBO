    private void loadNotifikasi() {
        DefaultTableModel model = (DefaultTableModel) tabelNotifikasi.getModel();
        model.setRowCount(0);

        List<Notification> list = notifRepo.getActiveNotifications(currentUser.getId());
        for (Notification n : list) {
            model.addRow(new Object[]{
                n.getId(),
                n.getScheduledTime().format(fmt),
                n.getMessage(),
                n.isRead() ? "Sudah Dibaca" : "BELUM DIBACA"
            });
        }
    }

