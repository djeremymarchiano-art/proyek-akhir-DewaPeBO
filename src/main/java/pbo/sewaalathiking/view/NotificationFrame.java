    private void btnBacaSemuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBacaSemuaActionPerformed
        if (notifRepo.markAllAsRead(currentUser.getId())) {
            loadNotifikasi();
        }
    }//GEN-LAST:event_btnBacaSemuaActionPerformed

    private void btnTandaiDibacaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTandaiDibacaActionPerformed
        int row = tabelNotifikasi.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih notifikasi terlebih dahulu!");
            return;
        }
        int notifId = Integer.parseInt(tabelNotifikasi.getValueAt(row, 0).toString());
        if (notifRepo.markAsRead(notifId)) {
            loadNotifikasi();
        }
    }//GEN-LAST:event_btnTandaiDibacaActionPerformed

    private void btnKembaliActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKembaliActionPerformed
        if ("ADMIN".equalsIgnoreCase(currentUser.getRole())) {
            new AdminDashboardFrame(currentUser).setVisible(true);
        } else {
            new CustomerMainFrame(currentUser).setVisible(true);
        }
        this.dispose();
    }//GEN-LAST:event_btnKembaliActionPerformed

