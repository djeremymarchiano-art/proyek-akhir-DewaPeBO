    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        String name = fieldName.getText().trim();
    String phone = fieldPhone.getText().trim();
    String email = fieldEmail.getText().trim();
    String password = new String(fieldPassword.getPassword());
    String confirm = new String(fieldConfirm.getPassword());

    // Validasi
    if (name.isEmpty() || phone.isEmpty() || email.isEmpty()
            || password.isEmpty() || confirm.isEmpty()) {
        warn("Semua field wajib diisi!");
        return;
    }
    if (!email.matches("^[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+$")) {
        warn("Format email tidak valid!");
        return;
    }
    if (!phone.matches("^[0-9+]{8,15}$")) {
        warn("No. Telepon harus 8-15 digit angka!");
        return;
    }
    if (password.length() < 6) {
        warn("Password minimal 6 karakter!");
        return;
    }
    if (!password.equals(confirm)) {
        warn("Konfirmasi password tidak cocok!");
        fieldConfirm.setText("");
        fieldConfirm.requestFocus();
        return;
    }
    if (userRepo.emailExists(email)) {
        warn("Email sudah terdaftar!");
        return;
    }

    // Pendaftaran publik selalu sebagai CUSTOMER
    User user = new User(0, "CUSTOMER", name, phone, email, password);

    if (userRepo.register(user)) {
        JOptionPane.showMessageDialog(this,
            "Registrasi berhasil! Silakan login.",
            "Sukses", JOptionPane.INFORMATION_MESSAGE);
        backToLogin();
    } else {
        JOptionPane.showMessageDialog(this,
            "Registrasi gagal. Periksa koneksi database.",
            "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnRegisterActionPerformed

