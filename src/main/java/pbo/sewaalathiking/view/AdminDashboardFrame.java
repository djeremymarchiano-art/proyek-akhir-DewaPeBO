    private void updateNotifBadge() {
        if (currentUser == null) return;
        int unread = notifRepo.getUnreadCount(currentUser.getId());
        if (unread > 0) {
            btnNotifikasi.setText("Notifikasi Pengingat (" + unread + ")");
        } else {
            btnNotifikasi.setText("Notifikasi Pengingat");
        }
    }

