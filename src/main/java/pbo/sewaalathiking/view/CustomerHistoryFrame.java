    private void loadRiwayat() {
        DefaultTableModel model = (DefaultTableModel) tabelRiwayat.getModel();
        model.setRowCount(0);

        List<RentalTransaction> list = rentalRepo.getRentalsByUserId(currentUser.getId());
        for (RentalTransaction tx : list) {
            String tglMulai = tx.getStartDate().format(fmt);
            String batasKembali = tx.getExpectedReturnDate().format(fmt);
            String tglKembali = (tx.getActualReturnDate() != null)
                    ? tx.getActualReturnDate().format(fmt)
                    : "-";

            model.addRow(new Object[]{
                tx.getId(),
                tglMulai,
                batasKembali,
                tglKembali,
                String.format("Rp %,.0f", tx.getTotalCost()),
                String.format("Rp %,.0f", tx.getPenaltyFee()),
                tx.getStatus()
            });
        }
    }

