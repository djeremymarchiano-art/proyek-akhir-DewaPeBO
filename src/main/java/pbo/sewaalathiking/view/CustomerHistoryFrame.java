    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int selectedRow = tabelRiwayat.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Pilih salah satu riwayat transaksi di tabel terlebih dahulu!");
        return;
    }

    int idSewa          = Integer.parseInt(tabelRiwayat.getValueAt(selectedRow, 0).toString());
    String mulai        = tabelRiwayat.getValueAt(selectedRow, 1).toString();
    String batasKembali = tabelRiwayat.getValueAt(selectedRow, 2).toString();
    String dikembalikan = tabelRiwayat.getValueAt(selectedRow, 3).toString();
    String biayaSewa    = tabelRiwayat.getValueAt(selectedRow, 4).toString();
    String denda        = tabelRiwayat.getValueAt(selectedRow, 5).toString();
    String status       = tabelRiwayat.getValueAt(selectedRow, 6).toString();

    // Ambil daftar alat dari RentalRepository
    String daftarAlat = rentalRepo.getTransactionItemsSummary(idSewa);
    if (daftarAlat == null || daftarAlat.isEmpty()) {
        daftarAlat = "(Tidak ada rincian alat)\n";
    }

    String detail = "=== DETAIL TRANSAKSI #" + idSewa + " ===\n"
            + "Mulai Sewa      : " + mulai + "\n"
            + "Batas Kembali   : " + batasKembali + "\n"
            + "Dikembalikan    : " + dikembalikan + "\n"
            + "Biaya Sewa      : " + biayaSewa + "\n"
            + "Denda           : " + denda + "\n"
            + "Status          : " + status + "\n"
            + "------------------------------------\n"
            + "Daftar Alat yang Disewa:\n"
            + daftarAlat;

    JOptionPane.showMessageDialog(this, detail, "Detail Peminjaman #" + idSewa, JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_jButton1ActionPerformed

