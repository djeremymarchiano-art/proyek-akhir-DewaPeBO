    private void setupTable() {
        DefaultTableModel model = new DefaultTableModel(
            new Object[]{"ID Alat", "Nama Alat", "Harga/Hari", "Qty", "Subtotal/Hari"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tabelKeranjang.setModel(model);
    }
    
    private void loadCartTable() {
        DefaultTableModel model = (DefaultTableModel) tabelKeranjang.getModel();
        model.setRowCount(0);
        for (Object[] item : cartList) {
            model.addRow(item);
        }
    }
    
    private void hitungTotalKeseluruhan() {
        double totalPerHari = 0;
        for (Object[] item : cartList) {
            totalPerHari += Double.parseDouble(item[4].toString());
        }

        int durasi = 1;
        try {
            String teks = fieldDurasi.getText().trim();
            if (!teks.isEmpty()) {
                durasi = Integer.parseInt(teks);
                if (durasi <= 0) durasi = 1;
            }
        } catch (NumberFormatException ignored) {}

        double grandTotal = totalPerHari * durasi;
        lblTotalBayar.setText("Rp " + String.format("%,.0f", grandTotal));
    }

