    private void btnCekBarangActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCekBarangActionPerformed
        int row = tabelTransaksi.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih transaksi pada tabel terlebih dahulu!");
            return;
        }
        int txId = Integer.parseInt(tabelTransaksi.getValueAt(row, 0).toString());
        String penyewa = tabelTransaksi.getValueAt(row, 1).toString();
        String daftarAlat = rentalRepo.getTransactionItemsSummary(txId);

        JOptionPane.showMessageDialog(this,
            "Rincian Alat Transaksi #" + txId + " (" + penyewa + "):\n\n" + daftarAlat,
            "Cek Kelengkapan Alat",
            JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnCekBarangActionPerformed

    private void btnProsesKembaliActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesKembaliActionPerformed
        int row = tabelTransaksi.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih transaksi yang akan dikembalikan!");
            return;
        }
        String status = tabelTransaksi.getValueAt(row, 7).toString();
        if (!"ACTIVE".equalsIgnoreCase(status)) {
            JOptionPane.showMessageDialog(this, "Transaksi ini sudah berstatus " + status + "!");
            return;
        }

        int txId = Integer.parseInt(tabelTransaksi.getValueAt(row, 0).toString());
        String penyewa = tabelTransaksi.getValueAt(row, 1).toString();
        String biayaSewa = tabelTransaksi.getValueAt(row, 5).toString();
        String denda = tabelTransaksi.getValueAt(row, 6).toString();
        String daftarAlat = rentalRepo.getTransactionItemsSummary(txId);

        int confirm = JOptionPane.showConfirmDialog(this,
            "Konfirmasi pengembalian untuk Transaksi #" + txId + " (" + penyewa + ")?\n\n" +
            "Alat yang dikembalikan:\n" + daftarAlat + "\n" +
            "Biaya Sewa : " + biayaSewa + "\n" +
            "Denda Telat : " + denda + "\n\n" +
            "Stok alat akan otomatis dikembalikan ke katalog.",
            "Konfirmasi Pengembalian",
            JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            if (rentalRepo.processReturn(txId)) {
                JOptionPane.showMessageDialog(this, "Pengembalian berhasil diproses dan stok telah dipulihkan!");
                loadTransaksi();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal memproses pengembalian.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnProsesKembaliActionPerformed

