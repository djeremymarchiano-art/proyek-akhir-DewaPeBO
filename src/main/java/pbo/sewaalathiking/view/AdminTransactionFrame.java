    private void setupTable() {
        DefaultTableModel model = new DefaultTableModel(
            new Object[]{"ID Sewa", "Penyewa", "Tgl Mulai", "Batas Kembali", "Tgl Kembali", "Biaya Sewa", "Denda", "Status"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tabelTransaksi.setModel(model);
    }
    private void loadTransaksi() {
        DefaultTableModel model = (DefaultTableModel) tabelTransaksi.getModel();
        model.setRowCount(0);

        List<Object[]> rows = rentalRepo.getAllTransactionsForAdmin();
        for (Object[] r : rows) {
            LocalDateTime start = (LocalDateTime) r[2];
            LocalDateTime expected = (LocalDateTime) r[3];
            LocalDateTime actual = (LocalDateTime) r[4];

            model.addRow(new Object[]{
                r[0],
                r[1],
                start.format(fmt),
                expected.format(fmt),
                (actual != null) ? actual.format(fmt) : "-",
                String.format("Rp %,.0f", (Double) r[5]),
                String.format("Rp %,.0f", (Double) r[6]),
                r[7]
            });
        }
    }

